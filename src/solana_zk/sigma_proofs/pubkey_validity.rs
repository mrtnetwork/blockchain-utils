//! Pubkey-validity Sigma proof (zero-dep port).
//!
//! /// Byte-compatible port of
//! `zk-sdk/src/sigma_proofs/pubkey_validity.rs`: Schnorr proof of knowledge
//! of `s` with `P = s^{-1} * H`. Transcript labels (`pubkey`, `pubkey-proof`
//! dom-sep, `Y`, challenge `c`) and proof layout (`Y || z`, 64 bytes) match
//! upstream exactly. Randomness comes from a caller-supplied 32-byte seed
//! driving ChaCha20 (same deterministic pattern as the Monero prover).

use crate::solana_zk::sigma_proofs::{
    canonical_scalar, decode_point, SigmaError, SolanaSigResult, ZkTranscript, is_identity_enc,
};
use crate::solana_zk::{h_point, SolanaZkError, SolanaZkResult};
use crate::curve::traits::CurvePoint;
use crate::rng::ChaCha20Rng;

/// Byte length of a pubkey-validity proof (`Y || z`).
pub const PUBKEY_VALIDITY_PROOF_LEN: usize = 64;

/// Draw a nonzero masking scalar from a seeded ChaCha20 stream.
fn masking_scalar(rng: &mut ChaCha20Rng) -> crate::curve::ed25519::Scalar {
    loop {
        let mut b = [0u8; 32];
        rng.next_bytes(32, &mut b);
        let s = crate::curve::ed25519::Scalar::from_bytes_mod_order(&b);
        if !s.is_zero() {
            return s;
        }
    }
}

/// Prove knowledge of the secret behind `P = s^{-1} * H`.
/// `context` is the transcript label (upstream tests use `b"test"`; the
/// token program fixes its own per-instruction label at the call site).
pub fn prove_pubkey_validity(
    secret: &[u8; 32],
    seed: &[u8; 32],
    context: &[u8],
) -> SolanaZkResult<[u8; 64]> {
    let s = crate::curve::ed25519::Scalar::from_bytes_le(secret)
        .map_err(|_| SolanaZkError::InvalidPoint)?;
    if s.is_zero() {
        return Err(SolanaZkError::InvalidPoint);
    }
    let s_inv = s.invert().map_err(|_| SolanaZkError::InvalidPoint)?;
    let h = h_point()?;
    let mut p_enc = [0u8; 32];
    h.mul(&s_inv)
        .to_bytes_compressed(&mut p_enc)
        .map_err(|_| SolanaZkError::InvalidPoint)?;

    let mut transcript = ZkTranscript::new(context);
    transcript.append_message(b"pubkey", &p_enc);
    transcript.pubkey_proof_domain_separator();

    let mut rng = ChaCha20Rng::from_seed(seed);
    let y = masking_scalar(&mut rng);
    let mut y_enc = [0u8; 32];
    h.mul(&y)
        .to_bytes_compressed(&mut y_enc)
        .map_err(|_| SolanaZkError::InvalidPoint)?;
    transcript.append_point(b"Y", &y_enc);
    let c = transcript.challenge_scalar(b"c");
    let z = c.mul(&s_inv).add(&y);
    let mut z_enc = [0u8; 32];
    z.to_bytes_le(&mut z_enc);
    let mut out = [0u8; 64];
    out[..32].copy_from_slice(&y_enc);
    out[32..].copy_from_slice(&z_enc);
    Ok(out)
}

/// Verify a pubkey-validity proof. Rejects identity pubkeys
/// even if the equation would hold (matches upstream).
pub fn verify_pubkey_validity(
    pubkey: &[u8; 32],
    proof: &[u8; 64],
    context: &[u8],
) -> SolanaSigResult<()> {
    let p = decode_point(pubkey)?;
    if p.ct_is_identity() == 1 {
        return Err(SigmaError::IdentityPoint);
    }
    let mut transcript = ZkTranscript::new(context);
    transcript.append_message(b"pubkey", pubkey);
    transcript.pubkey_proof_domain_separator();

    let y_enc: [u8; 32] = proof[..32]
        .try_into()
        .map_err(|_| SigmaError::Deserialization)?;
    transcript.validate_and_append_point(b"Y", &y_enc)?;
    let c = transcript.challenge_scalar(b"c");
    let z = canonical_scalar(&proof[32..])?;
    let y = decode_point(&y_enc)?;

    let h = h_point().map_err(|_| SigmaError::Deserialization)?;
    let check = h
        .mul(&z)
        .add(&p.mul(&c.neg()))
        .add(&y.neg());
    if is_identity_enc(&check) {
        Ok(())
    } else {
        Err(SigmaError::AlgebraicRelation)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Upstream golden vector (`pubkey_validity` test):
    /// proof generated by the official SDK verifies under `b"test"`.
    #[test]
    fn golden_vector_verifies() {
        let pubkey: [u8; 32] = [
            150, 18, 160, 189, 159, 177, 70, 194, 147, 71, 188, 31, 40, 217, 105,
            150, 219, 207, 102, 77, 15, 115, 147, 31, 167, 37, 101, 169, 25,
            131, 112, 9,
        ];
        let proof: [u8; 64] = [
            186, 216, 40, 44, 16, 13, 185, 84, 109, 188, 222, 216, 201, 154,
            212, 195, 61, 29, 100, 191, 142, 110, 192, 229, 70, 146, 93, 111,
            167, 171, 94, 36, 25, 88, 43, 100, 189, 22, 210, 39, 201, 146, 4,
            163, 239, 145, 168, 71, 186, 118, 161, 243, 66, 104, 161, 5, 170,
            132, 84, 23, 144, 224, 150, 7,
        ];
        verify_pubkey_validity(&pubkey, &proof, b"test").unwrap();
    }

    /// Prove/verify roundtrip with a fixed seed.
    #[test]
    fn roundtrip() {
        let secret = [11u8; 32];
        let pubkey =
            crate::solana_zk::elgamal_pubkey_from_secret(&secret).unwrap();
        let proof =
            prove_pubkey_validity(&secret, &[5u8; 32], b"test").unwrap();
        verify_pubkey_validity(&pubkey, &proof, b"test").unwrap();
        // Wrong context fails (transcript binding).
        assert!(verify_pubkey_validity(&pubkey, &proof, b"other").is_err());
        // Identity pubkey rejected.
        assert_eq!(
            verify_pubkey_validity(&[0u8; 32], &proof, b"test").unwrap_err(),
            SigmaError::IdentityPoint
        );
    }
}
